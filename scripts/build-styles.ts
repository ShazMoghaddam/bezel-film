import { readdir, readFile } from "node:fs/promises";
import { join } from "node:path";
import { fileURLToPath } from "node:url";
import { FONT_NAMES } from "../src/spec/fonts.js";
import { writeOrCheck } from "./write-or-check.js";

/**
 * Writes src/spec/styles.ts, the list of styles, from the folders in styles/.
 * Adding a style is adding its folder and running `npm run styles`. CI runs
 * `npm run styles:check`, so the list can't drift from the folders.
 */

const root = fileURLToPath(new URL("..", import.meta.url));
const dir = join(root, "styles");

interface StyleJson {
  name: string;
  label: string;
  description: string;
  theme: string;
  font: string;
}

const styles: StyleJson[] = [];
for (const entry of (await readdir(dir, { withFileTypes: true })).filter((e) => e.isDirectory()).sort((a, b) => a.name.localeCompare(b.name))) {
  const style = JSON.parse(await readFile(join(dir, entry.name, "style.json"), "utf8")) as StyleJson;
  const where = `styles/${entry.name}/style.json`;
  if (style.name !== entry.name) throw new Error(`${where}: "name" is "${style.name}", but the folder is "${entry.name}"`);
  if (!/^[a-z0-9]+(-[a-z0-9]+)*$/.test(style.name)) throw new Error(`${where}: name it in lowercase words joined by hyphens`);
  if (style.theme !== "dark" && style.theme !== "light") throw new Error(`${where}: "theme" must be "dark" or "light"`);
  if (!(FONT_NAMES as readonly string[]).includes(style.font)) throw new Error(`${where}: "font" must be one of ${FONT_NAMES.join(", ")}`);
  styles.push(style);
}

const info = styles
  .map((s) => `  { name: ${JSON.stringify(s.name)}, label: ${JSON.stringify(s.label)}, description: ${JSON.stringify(s.description)}, theme: ${JSON.stringify(s.theme)}, font: ${JSON.stringify(s.font)} },`)
  .join("\n");

const source = `// Generated by \`npm run styles\` from the folders in styles/. Don't edit by hand.
import type { FontName } from "./fonts.js";

export const STYLES = [${styles.map((s) => JSON.stringify(s.name)).join(", ")}] as const;
export type StyleName = (typeof STYLES)[number];

export interface StyleInfo {
  name: StyleName;
  label: string;
  description: string;
  theme: "dark" | "light";
  font: FontName;
}

export const STYLE_INFO: readonly StyleInfo[] = [
${info}
];
`;

await writeOrCheck(new Map([[join(root, "src/spec/styles.ts"), source]]), root);
